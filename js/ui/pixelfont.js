/** 缺字时画的方框，比默默画个空格更容易在开发期发现 */
const MISSING = ['.###.', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.'];

/** 取字形（找不到返回缺字框） */
export function glyph(ch) {
  return GLYPHS[ch] || GLYPHS[String(ch).toUpperCase()] || MISSING;
}

/** 一串文字按点阵排下来占多宽（正好是 bodySize 里用的那个公式） */
export function textWidth(text) {
  return Math.max(1, text.length) * GLYPH_PITCH - 1;
}

/**
 * 在 canvas 上画一串点阵文字，左上角对齐 (x, y)。
 *
 * 同一行里连续的实心像素会被合并成一个 fillRect——一个 30 字的 HUD 每帧
 * 约 1000 次 fillRect，合并后降到 200 次左右，没必要为此上 ImageData。
 *
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {string} color CSS 颜色
 * @returns {number} 画完后的右边界 x
 */
export function drawText(ctx, text, x, y, color) {
  ctx.fillStyle = color;
  let cx = x;
  for (const raw of String(text)) {
    const rows = glyph(raw);
    for (let ry = 0; ry < GLYPH_H; ry++) {
      const row = rows[ry];
      let run = 0;
      for (let rx = 0; rx <= GLYPH_W; rx++) {
        const solid = rx < GLYPH_W && row[rx] === '#';
        if (solid) {
          run++;
        } else if (run) {
          ctx.fillRect(cx + rx - run, y + ry, run, 1);
          run = 0;
        }
      }
    }
    cx += GLYPH_PITCH;
  }
  return cx - 1;
}

/** 居中绘制：给定中心 x 与基线 y（左上角），返回左边界 */
export function drawTextCentered(ctx, text, centerX, y, color) {
  const w = textWidth(text);
  const x = Math.round(centerX - w / 2);
  drawText(ctx, text, x, y, color);
  return x;
}

