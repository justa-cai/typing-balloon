// 汉字点阵
// ──────────────────────────────────────────────────────────────────────

/** 二值化阈值：alpha 大于它才算实心 */
const HANZI_ALPHA = 110;

/** 汉字点阵缓存：一个汉字只光栅化一次 */
const hanziCache = new Map();

/**
 * 把一个汉字光栅化成 size×size 的 1bit 点阵。
 *
 * 做法：离屏 canvas 用系统字体画黑底白字 → 读像素 → 按 alpha 阈值二值化。
 * 结果按字缓存，整局只算一次。
 *
 * @param {string} ch  单个汉字
 * @param {number} [size] 点阵边长，默认 16（FC 汉字字库的常见规格）
 * @returns {{size: number, rows: Uint8Array}} rows 长度 size*size，1 为实心
 */
export function hanziTile(ch, size = 16) {
  const key = ch + '@' + size;
  const hit = hanziCache.get(key);
  if (hit) return hit;

  const off = document.createElement('canvas');
  off.width = size;
  off.height = size;
  const g = off.getContext('2d', { willReadFrequently: true });

  g.fillStyle = '#000';
  g.fillRect(0, 0, size, size);
  g.fillStyle = '#fff';
  // 字号略小于格子，给笔画留出边距，否则复杂字会糊成一团
  g.font = `${Math.round(size * 0.9)}px "Noto Sans CJK SC", "Source Han Sans SC", ` +
           `"PingFang SC", "Microsoft YaHei", "WenQuanYi Micro Hei", sans-serif`;
  g.textAlign = 'center';
  g.textBaseline = 'middle';
  g.fillText(ch, size / 2, size / 2 + 1);

  const data = g.getImageData(0, 0, size, size).data;
  const rows = new Uint8Array(size * size);
  for (let i = 0; i < size * size; i++) {
    rows[i] = data[i * 4] > HANZI_ALPHA ? 1 : 0;
  }

  const tile = { size, rows };
  hanziCache.set(key, tile);
  return tile;
}

/**
 * 把汉字点阵画到 canvas 上，左上角对齐 (x, y)。
 * 同样做行内游程合并。
 *
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} ch
 * @param {number} x
 * @param {number} y
 * @param {string} color
 * @param {number} size 点阵边长，默认 16
 */
export function drawHanzi(ctx, ch, x, y, color, size = 16) {
  const tile = hanziTile(ch, size);
  const n = tile.size;
  ctx.fillStyle = color;
  for (let ry = 0; ry < n; ry++) {
    let run = 0;
    for (let rx = 0; rx <= n; rx++) {
      const solid = rx < n && tile.rows[ry * n + rx] === 1;
      if (solid) {
        run++;
      } else if (run) {
        ctx.fillRect(x + rx - run, y + ry, run, 1);
        run = 0;
      }
    }
  }
}
